"""Entity taxonomy, gazetteers and classification heuristics for Phase 3.

The taxonomy is intentionally explicit.  spaCy's built-in NER supplies generic
labels (``ORG``, ``GPE``, ``LOC`` ...), while the supply-chain terms in this
module let the extractor recognise ports, facilities, materials, industries and
products that the small English model does not know about.

The lists are gazetteers, not sample answers: they are matched against whatever
text an article contains and never inject an entity that is absent from that
text.
"""

